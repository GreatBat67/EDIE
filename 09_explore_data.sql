SELECT RETENTION_ACTION, COUNT(*) AS CNT
FROM ANALYTICS.AT_RISK_POLICIES GROUP BY RETENTION_ACTION ORDER BY CNT DESC;

-- High churn + high revenue at risk (top 10)
SELECT RISK_ID, POLICY_ID, CUSTOMER_ID, CHURN_PROBABILITY, REVENUE_AT_RISK, MISSED_PAYMENTS_COUNT, NPS_SCORE
FROM ANALYTICS.AT_RISK_POLICIES
ORDER BY CHURN_PROBABILITY * REVENUE_AT_RISK DESC
LIMIT 10;

