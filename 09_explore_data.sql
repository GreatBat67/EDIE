USE DATABASE INSURANCE_AI_HUB;
USE WAREHOUSE INSURANCE_AI_HUB_WH;

-- ============================================================
-- 1. FULL INVENTORY: All tables with row counts and columns
-- ============================================================
SELECT
    t.TABLE_SCHEMA,
    t.TABLE_NAME,
    t.ROW_COUNT,
    c.COL_COUNT AS COLUMN_COUNT,
    t.BYTES / 1024 / 1024 AS SIZE_MB,
    t.COMMENT
FROM INFORMATION_SCHEMA.TABLES t
LEFT JOIN (
    SELECT TABLE_SCHEMA, TABLE_NAME, COUNT(*) AS COL_COUNT
    FROM INFORMATION_SCHEMA.COLUMNS
    WHERE TABLE_SCHEMA IN ('ANALYTICS','DOCUMENTS','DATA_QUALITY')
    GROUP BY TABLE_SCHEMA, TABLE_NAME
) c ON t.TABLE_SCHEMA = c.TABLE_SCHEMA AND t.TABLE_NAME = c.TABLE_NAME
WHERE t.TABLE_SCHEMA IN ('ANALYTICS','DOCUMENTS','DATA_QUALITY')
ORDER BY t.TABLE_SCHEMA, t.TABLE_NAME;

-- ============================================================
-- 2. COLUMN DETAILS: All 149 columns with types
-- ============================================================
SELECT
    TABLE_SCHEMA,
    TABLE_NAME,
    ORDINAL_POSITION,
    COLUMN_NAME,
    DATA_TYPE,
    IS_NULLABLE,
    COLUMN_DEFAULT
FROM INFORMATION_SCHEMA.COLUMNS
WHERE TABLE_SCHEMA IN ('ANALYTICS','DOCUMENTS','DATA_QUALITY')
ORDER BY TABLE_SCHEMA, TABLE_NAME, ORDINAL_POSITION;

-- ============================================================
-- 3. CUSTOMERS - Sample & Distribution
-- ============================================================
SELECT * FROM ANALYTICS.CUSTOMERS LIMIT 10;

SELECT RISK_TIER, COUNT(*) AS CNT, ROUND(AVG(CREDIT_SCORE)) AS AVG_CREDIT
FROM ANALYTICS.CUSTOMERS GROUP BY RISK_TIER ORDER BY CNT DESC;

SELECT SEGMENT, COUNT(*) AS CNT FROM ANALYTICS.CUSTOMERS GROUP BY SEGMENT ORDER BY CNT DESC;

SELECT STATE, COUNT(*) AS CNT FROM ANALYTICS.CUSTOMERS GROUP BY STATE ORDER BY CNT DESC LIMIT 10;

SELECT
    'Null Emails' AS METRIC, COUNT(*) AS VALUE FROM ANALYTICS.CUSTOMERS WHERE EMAIL IS NULL
UNION ALL SELECT 'Null Phones', COUNT(*) FROM ANALYTICS.CUSTOMERS WHERE PHONE IS NULL
UNION ALL SELECT 'Duplicate Names', COUNT(*) FROM ANALYTICS.CUSTOMERS WHERE CUSTOMER_ID LIKE 'CUST-D%';

-- ============================================================
-- 4. AGENTS - Sample & Distribution
-- ============================================================
SELECT * FROM ANALYTICS.AGENTS LIMIT 10;

SELECT REGION, COUNT(*) AS CNT, ROUND(AVG(PERFORMANCE_RATING), 2) AS AVG_RATING
FROM ANALYTICS.AGENTS GROUP BY REGION ORDER BY CNT DESC;

SELECT SPECIALIZATION, COUNT(*) AS CNT FROM ANALYTICS.AGENTS GROUP BY SPECIALIZATION ORDER BY CNT DESC;

SELECT STATUS, COUNT(*) AS CNT FROM ANALYTICS.AGENTS GROUP BY STATUS;

-- Low performers with high policy counts (injected anomaly)
SELECT AGENT_ID, AGENT_NAME, REGION, PERFORMANCE_RATING, ACTIVE_POLICIES_COUNT
FROM ANALYTICS.AGENTS
WHERE PERFORMANCE_RATING < 2.0 AND ACTIVE_POLICIES_COUNT > 75
ORDER BY PERFORMANCE_RATING;

-- ============================================================
-- 5. POLICIES - Sample & Distribution
-- ============================================================
SELECT * FROM ANALYTICS.POLICIES LIMIT 10;

SELECT POLICY_TYPE, COUNT(*) AS CNT, ROUND(AVG(PREMIUM_AMOUNT), 2) AS AVG_PREMIUM,
       ROUND(AVG(COVERAGE_AMOUNT), 0) AS AVG_COVERAGE
FROM ANALYTICS.POLICIES GROUP BY POLICY_TYPE ORDER BY CNT DESC;

SELECT PLAN_TIER, COUNT(*) AS CNT, ROUND(AVG(DEDUCTIBLE), 2) AS AVG_DEDUCTIBLE
FROM ANALYTICS.POLICIES GROUP BY PLAN_TIER ORDER BY CNT DESC;

SELECT STATUS, COUNT(*) AS CNT FROM ANALYTICS.POLICIES GROUP BY STATUS ORDER BY CNT DESC;

SELECT RENEWAL_STATUS, COUNT(*) AS CNT FROM ANALYTICS.POLICIES GROUP BY RENEWAL_STATUS ORDER BY CNT DESC;

-- Premium outliers (injected)
SELECT POLICY_ID, POLICY_TYPE, PREMIUM_AMOUNT, COVERAGE_AMOUNT
FROM ANALYTICS.POLICIES WHERE PREMIUM_AMOUNT > 10000 ORDER BY PREMIUM_AMOUNT DESC;

-- ============================================================
-- 6. CLAIMS - Sample & Distribution
-- ============================================================
SELECT * FROM ANALYTICS.CLAIMS LIMIT 10;

SELECT CLAIM_TYPE, COUNT(*) AS CNT, ROUND(AVG(CLAIM_AMOUNT), 2) AS AVG_AMOUNT,
       ROUND(AVG(FRAUD_SCORE), 2) AS AVG_FRAUD
FROM ANALYTICS.CLAIMS GROUP BY CLAIM_TYPE ORDER BY CNT DESC;

SELECT STATUS, COUNT(*) AS CNT FROM ANALYTICS.CLAIMS GROUP BY STATUS ORDER BY CNT DESC;

-- Seasonal distribution (monthly)
SELECT DATE_TRUNC('month', CLAIM_DATE) AS MONTH, COUNT(*) AS CLAIMS
FROM ANALYTICS.CLAIMS GROUP BY MONTH ORDER BY MONTH;

-- Fraud score distribution
SELECT
    CASE
        WHEN FRAUD_SCORE < 20 THEN '0-20 (Low)'
        WHEN FRAUD_SCORE < 40 THEN '20-40 (Normal)'
        WHEN FRAUD_SCORE < 60 THEN '40-60 (Elevated)'
        WHEN FRAUD_SCORE < 80 THEN '60-80 (High)'
        ELSE '80-100 (Critical)'
    END AS FRAUD_BAND,
    COUNT(*) AS CNT
FROM ANALYTICS.CLAIMS GROUP BY FRAUD_BAND ORDER BY FRAUD_BAND;

-- Resolution days distribution
SELECT
    CASE
        WHEN RESOLUTION_DAYS <= 30 THEN '0-30 days'
        WHEN RESOLUTION_DAYS <= 90 THEN '31-90 days'
        WHEN RESOLUTION_DAYS <= 180 THEN '91-180 days'
        ELSE '180+ days'
    END AS RESOLUTION_BAND,
    COUNT(*) AS CNT, ROUND(AVG(FRICTION_SCORE), 2) AS AVG_FRICTION
FROM ANALYTICS.CLAIMS GROUP BY RESOLUTION_BAND ORDER BY RESOLUTION_BAND;

-- Hurricane claims (injected seasonal spike)
SELECT CAUSE_OF_LOSS, COUNT(*) AS CNT, ROUND(AVG(CLAIM_AMOUNT), 2) AS AVG_AMT
FROM ANALYTICS.CLAIMS
WHERE CAUSE_OF_LOSS = 'Hurricane/Tropical Storm'
GROUP BY CAUSE_OF_LOSS;

-- ============================================================
-- 7. BILLING - Sample & Distribution
-- ============================================================
SELECT * FROM ANALYTICS.BILLING LIMIT 10;

SELECT PAYMENT_STATUS, COUNT(*) AS CNT,
       ROUND(SUM(OUTSTANDING_BALANCE), 2) AS TOTAL_OUTSTANDING,
       ROUND(SUM(LATE_FEE), 2) AS TOTAL_LATE_FEES
FROM ANALYTICS.BILLING GROUP BY PAYMENT_STATUS ORDER BY CNT DESC;

SELECT PAYMENT_METHOD, COUNT(*) AS CNT
FROM ANALYTICS.BILLING WHERE PAYMENT_METHOD IS NOT NULL GROUP BY PAYMENT_METHOD ORDER BY CNT DESC;

-- Delinquency rate by month
SELECT DATE_TRUNC('month', INVOICE_DATE) AS MONTH,
       COUNT(*) AS TOTAL_INVOICES,
       SUM(CASE WHEN PAYMENT_STATUS = 'Overdue' THEN 1 ELSE 0 END) AS OVERDUE,
       ROUND(SUM(CASE WHEN PAYMENT_STATUS = 'Overdue' THEN 1 ELSE 0 END) * 100.0 / COUNT(*), 2) AS OVERDUE_PCT
FROM ANALYTICS.BILLING GROUP BY MONTH ORDER BY MONTH DESC LIMIT 12;

-- ============================================================
-- 8. AT_RISK_POLICIES - Sample & Distribution
-- ============================================================
SELECT * FROM ANALYTICS.AT_RISK_POLICIES LIMIT 10;

SELECT RISK_CATEGORY, COUNT(*) AS CNT,
       ROUND(AVG(CHURN_PROBABILITY), 4) AS AVG_CHURN_PROB,
       ROUND(SUM(REVENUE_AT_RISK), 2) AS TOTAL_REVENUE_AT_RISK
