-- ============================================================
-- 12. DQ_RESULTS - Execution History
-- ============================================================
SELECT * FROM DATA_QUALITY.DQ_RESULTS ORDER BY RUN_DATE DESC LIMIT 10;

SELECT STATUS, COUNT(*) AS CNT FROM DATA_QUALITY.DQ_RESULTS GROUP BY STATUS ORDER BY CNT DESC;

-- Rules that fail most often
SELECT r.RULE_NAME, r.TARGET_TABLE, r.SEVERITY, COUNT(*) AS FAIL_COUNT
FROM DATA_QUALITY.DQ_RESULTS res
JOIN DATA_QUALITY.DQ_RULES r ON res.RULE_ID = r.RULE_ID
WHERE res.STATUS = 'Fail'
GROUP BY r.RULE_NAME, r.TARGET_TABLE, r.SEVERITY
ORDER BY FAIL_COUNT DESC
LIMIT 10;

-- ============================================================
-- 13. DQ_SCORES - Table Health Over Time
-- ============================================================
SELECT * FROM DATA_QUALITY.DQ_SCORES ORDER BY SCORE_DATE DESC LIMIT 10;

-- Latest score per table
SELECT TABLE_NAME, OVERALL_SCORE, COMPLETENESS_SCORE, VALIDITY_SCORE, TIMELINESS_SCORE, TREND, SCORE_DATE
FROM DATA_QUALITY.DQ_SCORES
QUALIFY ROW_NUMBER() OVER (PARTITION BY TABLE_NAME ORDER BY SCORE_DATE DESC) = 1
ORDER BY OVERALL_SCORE;

-- ============================================================
-- 14. DQ_COLUMN_HEALTH - Column-Level Issues
-- ============================================================
SELECT * FROM DATA_QUALITY.DQ_COLUMN_HEALTH ORDER BY CHECK_DATE DESC LIMIT 10;

-- Unhealthiest columns
SELECT TABLE_NAME, COLUMN_NAME, ROUND(AVG(HEALTH_SCORE), 2) AS AVG_HEALTH,
       ROUND(AVG(NULL_RATE), 2) AS AVG_NULL_RATE,
       ROUND(AVG(OUTLIER_RATE), 2) AS AVG_OUTLIER_RATE,
       MAX(STATUS) AS WORST_STATUS
FROM DATA_QUALITY.DQ_COLUMN_HEALTH
GROUP BY TABLE_NAME, COLUMN_NAME
ORDER BY AVG_HEALTH
LIMIT 15;

-- ============================================================
-- 15. CROSS-TABLE ANALYTICS (Join Queries)
-- ============================================================

-- Customer 360: Full customer view with policies, claims, billing
SELECT
    c.CUSTOMER_ID, c.FIRST_NAME || ' ' || c.LAST_NAME AS FULL_NAME,
    c.RISK_TIER, c.CREDIT_SCORE, c.SEGMENT,
    COUNT(DISTINCT p.POLICY_ID) AS POLICY_COUNT,
    COUNT(DISTINCT cl.CLAIM_ID) AS CLAIM_COUNT,
    ROUND(SUM(DISTINCT p.PREMIUM_AMOUNT), 2) AS TOTAL_PREMIUMS,
    ROUND(COALESCE(SUM(b.OUTSTANDING_BALANCE), 0), 2) AS TOTAL_OUTSTANDING
FROM ANALYTICS.CUSTOMERS c
LEFT JOIN ANALYTICS.POLICIES p ON c.CUSTOMER_ID = p.CUSTOMER_ID
LEFT JOIN ANALYTICS.CLAIMS cl ON c.CUSTOMER_ID = cl.CUSTOMER_ID
LEFT JOIN ANALYTICS.BILLING b ON c.CUSTOMER_ID = b.CUSTOMER_ID AND b.PAYMENT_STATUS = 'Overdue'
GROUP BY c.CUSTOMER_ID, FULL_NAME, c.RISK_TIER, c.CREDIT_SCORE, c.SEGMENT
ORDER BY TOTAL_OUTSTANDING DESC
LIMIT 20;

-- Agent Performance: Claims + Policies + Risk
SELECT
    a.AGENT_ID, a.AGENT_NAME, a.REGION, a.SPECIALIZATION, a.PERFORMANCE_RATING,
    COUNT(DISTINCT p.POLICY_ID) AS POLICIES_MANAGED,
    COUNT(DISTINCT cl.CLAIM_ID) AS CLAIMS_ON_POLICIES,
    COUNT(DISTINCT ar.RISK_ID) AS AT_RISK_COUNT,
    ROUND(SUM(ar.REVENUE_AT_RISK), 2) AS TOTAL_REVENUE_AT_RISK
FROM ANALYTICS.AGENTS a
LEFT JOIN ANALYTICS.POLICIES p ON a.AGENT_ID = p.AGENT_ID
LEFT JOIN ANALYTICS.CLAIMS cl ON p.POLICY_ID = cl.POLICY_ID
LEFT JOIN ANALYTICS.AT_RISK_POLICIES ar ON p.POLICY_ID = ar.POLICY_ID
GROUP BY a.AGENT_ID, a.AGENT_NAME, a.REGION, a.SPECIALIZATION, a.PERFORMANCE_RATING
ORDER BY TOTAL_REVENUE_AT_RISK DESC NULLS LAST
LIMIT 20;

-- Claims by Region (for the "North Region spike" demo)
SELECT
    a.REGION,
    DATE_TRUNC('month', cl.CLAIM_DATE) AS MONTH,
    COUNT(*) AS CLAIM_COUNT,
    ROUND(SUM(cl.CLAIM_AMOUNT), 2) AS TOTAL_CLAIMED,
    ROUND(AVG(cl.FRAUD_SCORE), 2) AS AVG_FRAUD_SCORE
FROM ANALYTICS.CLAIMS cl
JOIN ANALYTICS.POLICIES p ON cl.POLICY_ID = p.POLICY_ID
JOIN ANALYTICS.AGENTS a ON p.AGENT_ID = a.AGENT_ID
WHERE cl.CLAIM_DATE >= '2024-01-01'
GROUP BY a.REGION, MONTH
ORDER BY a.REGION, MONTH;

-- Revenue at Risk by Policy Type
SELECT
    p.POLICY_TYPE,
    COUNT(*) AS AT_RISK_COUNT,
    ROUND(SUM(ar.REVENUE_AT_RISK), 2) AS TOTAL_REVENUE_AT_RISK,
    ROUND(AVG(ar.CHURN_PROBABILITY), 4) AS AVG_CHURN_PROB,
    ROUND(AVG(ar.MISSED_PAYMENTS_COUNT), 1) AS AVG_MISSED_PAYMENTS
FROM ANALYTICS.AT_RISK_POLICIES ar
JOIN ANALYTICS.POLICIES p ON ar.POLICY_ID = p.POLICY_ID
GROUP BY p.POLICY_TYPE
ORDER BY TOTAL_REVENUE_AT_RISK DESC;
