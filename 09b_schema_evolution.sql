-- ############################################################################
-- 1. CUSTOMERS — Add 5 columns
-- ############################################################################
USE SCHEMA ANALYTICS;

ALTER TABLE CUSTOMERS ADD COLUMN IF NOT EXISTS SALESFORCE_ACCOUNT_ID VARCHAR(20);
ALTER TABLE CUSTOMERS ADD COLUMN IF NOT EXISTS PREFERRED_CONTACT_METHOD VARCHAR(10);
ALTER TABLE CUSTOMERS ADD COLUMN IF NOT EXISTS HOUSEHOLD_ID VARCHAR(20);
ALTER TABLE CUSTOMERS ADD COLUMN IF NOT EXISTS LIFE_EVENT_FLAG VARCHAR(20);
ALTER TABLE CUSTOMERS ADD COLUMN IF NOT EXISTS ANNUAL_INCOME_RANGE VARCHAR(15);

UPDATE CUSTOMERS SET
    SALESFORCE_ACCOUNT_ID = 'SF-' || LPAD(SUBSTR(CUSTOMER_ID, 6), 7, '0'),
    PREFERRED_CONTACT_METHOD = CASE MOD(ABS(HASH(CUSTOMER_ID || 'pcm')), 4)
        WHEN 0 THEN 'Email' WHEN 1 THEN 'Phone' WHEN 2 THEN 'SMS' ELSE 'Mail' END,
    HOUSEHOLD_ID = 'HH-' || LPAD((MOD(ABS(HASH(CUSTOMER_ID || 'hh')), 3000) + 1)::VARCHAR, 5, '0'),
    LIFE_EVENT_FLAG = CASE MOD(ABS(HASH(CUSTOMER_ID || 'le')), 10)
        WHEN 0 THEN 'Marriage' WHEN 1 THEN 'NewHome' WHEN 2 THEN 'NewChild'
        WHEN 3 THEN 'Retirement' WHEN 4 THEN 'Relocation' ELSE 'None' END,
    ANNUAL_INCOME_RANGE = CASE
        WHEN CREDIT_SCORE >= 750 THEN CASE MOD(ABS(HASH(CUSTOMER_ID || 'inc')), 3)
            WHEN 0 THEN '100K-150K' WHEN 1 THEN '150K-200K' ELSE '200K+' END
        WHEN CREDIT_SCORE >= 650 THEN CASE MOD(ABS(HASH(CUSTOMER_ID || 'inc')), 3)
            WHEN 0 THEN '75K-100K' WHEN 1 THEN '100K-150K' ELSE '50K-75K' END
        WHEN CREDIT_SCORE >= 550 THEN CASE MOD(ABS(HASH(CUSTOMER_ID || 'inc')), 2)
            WHEN 0 THEN '50K-75K' ELSE '35K-50K' END
        ELSE CASE MOD(ABS(HASH(CUSTOMER_ID || 'inc')), 2)
            WHEN 0 THEN '25K-35K' ELSE 'Under 25K' END
    END
WHERE SALESFORCE_ACCOUNT_ID IS NULL;


-- ############################################################################
-- 2. AGENTS — Add 7 columns (APPLICATION_DATE handled in 10_close_kpi_gaps)
-- ############################################################################

ALTER TABLE AGENTS ADD COLUMN IF NOT EXISTS AGENCY_NAME VARCHAR(100);
ALTER TABLE AGENTS ADD COLUMN IF NOT EXISTS PRODUCER_CODE VARCHAR(20);
ALTER TABLE AGENTS ADD COLUMN IF NOT EXISTS COMMISSION_RATE NUMBER(4,3);
ALTER TABLE AGENTS ADD COLUMN IF NOT EXISTS TOTAL_PREMIUM_BOOK NUMBER(14,2);
ALTER TABLE AGENTS ADD COLUMN IF NOT EXISTS RETENTION_RATE NUMBER(4,3);
ALTER TABLE AGENTS ADD COLUMN IF NOT EXISTS NPS_SCORE NUMBER(3,0);
ALTER TABLE AGENTS ADD COLUMN IF NOT EXISTS APPOINTMENT_STATUS VARCHAR(15);

UPDATE AGENTS SET
    AGENCY_NAME = CASE MOD(ABS(HASH(AGENT_ID || 'ag')), 12)
        WHEN 0 THEN 'Pinnacle Insurance Group'
        WHEN 1 THEN 'Heartland Risk Advisors'
        WHEN 2 THEN 'Coastal Shield Insurance'
        WHEN 3 THEN 'Summit Financial Partners'
        WHEN 4 THEN 'Liberty Star Agency'
        WHEN 5 THEN 'Guardian Oak Insurance'
        WHEN 6 THEN 'Evergreen Risk Solutions'
        WHEN 7 THEN 'Atlas Coverage Group'
        WHEN 8 THEN 'Beacon Insurance Services'
        WHEN 9 THEN 'Cornerstone Risk Partners'
        WHEN 10 THEN 'Meridian Insurance Agency'
        ELSE 'Vanguard Protection Group'
    END,
    PRODUCER_CODE = 'PC-' || LPAD(SUBSTR(AGENT_ID, 5), 5, '0'),
    COMMISSION_RATE = ROUND(CASE SPECIALIZATION
        WHEN 'Commercial' THEN 0.08 + MOD(ABS(HASH(AGENT_ID || 'cr')), 50) / 1000.0
        WHEN 'Life' THEN 0.10 + MOD(ABS(HASH(AGENT_ID || 'cr')), 50) / 1000.0
        WHEN 'Health' THEN 0.06 + MOD(ABS(HASH(AGENT_ID || 'cr')), 40) / 1000.0
        WHEN 'Home' THEN 0.07 + MOD(ABS(HASH(AGENT_ID || 'cr')), 45) / 1000.0
        ELSE 0.05 + MOD(ABS(HASH(AGENT_ID || 'cr')), 50) / 1000.0
    END, 3),
    TOTAL_PREMIUM_BOOK = ROUND(ACTIVE_POLICIES_COUNT *
        CASE SPECIALIZATION
            WHEN 'Commercial' THEN 2500 WHEN 'Home' THEN 350 WHEN 'Health' THEN 500
            WHEN 'Life' THEN 200 ELSE 300
        END * (0.8 + MOD(ABS(HASH(AGENT_ID || 'tpb')), 40) / 100.0), 2),
    RETENTION_RATE = ROUND(CASE
        WHEN PERFORMANCE_RATING >= 4.0 THEN 0.88 + MOD(ABS(HASH(AGENT_ID || 'rr')), 100) / 1000.0
        WHEN PERFORMANCE_RATING >= 3.0 THEN 0.78 + MOD(ABS(HASH(AGENT_ID || 'rr')), 100) / 1000.0
        WHEN PERFORMANCE_RATING >= 2.0 THEN 0.68 + MOD(ABS(HASH(AGENT_ID || 'rr')), 100) / 1000.0
        ELSE 0.55 + MOD(ABS(HASH(AGENT_ID || 'rr')), 150) / 1000.0
    END, 3),
    NPS_SCORE = CASE
        WHEN PERFORMANCE_RATING >= 4.0 THEN 40 + MOD(ABS(HASH(AGENT_ID || 'nps')), 50)
        WHEN PERFORMANCE_RATING >= 3.0 THEN 10 + MOD(ABS(HASH(AGENT_ID || 'nps')), 40)
        WHEN PERFORMANCE_RATING >= 2.0 THEN -10 + MOD(ABS(HASH(AGENT_ID || 'nps')), 30)
        ELSE -20 + MOD(ABS(HASH(AGENT_ID || 'nps')), 20)
    END,
    APPOINTMENT_STATUS = CASE
        WHEN STATUS = 'Inactive' THEN 'Terminated'
        WHEN PERFORMANCE_RATING < 2.0 THEN 'Probationary'
        ELSE 'Active'
    END
WHERE AGENCY_NAME IS NULL;


