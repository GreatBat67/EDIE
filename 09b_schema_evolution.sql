-- ############################################################################

ALTER TABLE BILLING ALTER COLUMN PAYMENT_STATUS SET DATA TYPE VARCHAR(20);

ALTER TABLE BILLING ADD COLUMN IF NOT EXISTS BILLING_PLAN VARCHAR(15);
ALTER TABLE BILLING ADD COLUMN IF NOT EXISTS INSTALLMENT_NUMBER NUMBER(3,0);
ALTER TABLE BILLING ADD COLUMN IF NOT EXISTS TOTAL_INSTALLMENTS NUMBER(3,0);
ALTER TABLE BILLING ADD COLUMN IF NOT EXISTS GRACE_PERIOD_END DATE;
ALTER TABLE BILLING ADD COLUMN IF NOT EXISTS TRANSACTION_REF VARCHAR(30);
ALTER TABLE BILLING ADD COLUMN IF NOT EXISTS CANCELLATION_DATE DATE;

UPDATE BILLING SET
    BILLING_PLAN = CASE MOD(ABS(HASH(INVOICE_ID || 'bp')), 4)
        WHEN 0 THEN 'Monthly' WHEN 1 THEN 'Monthly' WHEN 2 THEN 'Quarterly' ELSE 'Annual' END,
    INSTALLMENT_NUMBER = MOD(ABS(HASH(INVOICE_ID || 'in')), 12) + 1,
    TOTAL_INSTALLMENTS = CASE MOD(ABS(HASH(INVOICE_ID || 'bp')), 4)
        WHEN 0 THEN 12 WHEN 1 THEN 12 WHEN 2 THEN 4 ELSE 1 END,
    GRACE_PERIOD_END = DATEADD('day', 15, DUE_DATE),
    TRANSACTION_REF = CASE
        WHEN PAYMENT_STATUS IN ('Paid','Partial') AND PAYMENT_DATE IS NOT NULL
        THEN 'TXN-' || LPAD(ABS(HASH(INVOICE_ID || 'txn'))::VARCHAR, 12, '0')
        ELSE NULL
    END,
    CANCELLATION_DATE = NULL
WHERE BILLING_PLAN IS NULL;

-- Remap old payment statuses to new values
UPDATE BILLING SET PAYMENT_STATUS = 'PastDue' WHERE PAYMENT_STATUS = 'Overdue';
UPDATE BILLING SET PAYMENT_STATUS = 'InGracePeriod'
WHERE PAYMENT_STATUS = 'Pending'
  AND MOD(ABS(HASH(INVOICE_ID || 'gp')), 100) < 30;
UPDATE BILLING SET PAYMENT_STATUS = 'Waived'
WHERE PAYMENT_STATUS = 'Paid'
  AND AMOUNT_DUE < 10
  AND MOD(ABS(HASH(INVOICE_ID || 'wv')), 100) < 5;
UPDATE BILLING SET PAYMENT_STATUS = 'Refunded'
WHERE PAYMENT_STATUS = 'Paid'
  AND MOD(ABS(HASH(INVOICE_ID || 'rf')), 100) < 2;
UPDATE BILLING SET PAYMENT_STATUS = 'SentToCollections'
WHERE PAYMENT_STATUS = 'PastDue'
  AND LATE_FEE > 50
  AND MOD(ABS(HASH(INVOICE_ID || 'sc')), 100) < 20;


