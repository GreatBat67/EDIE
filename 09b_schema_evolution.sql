    SCORE_DATE = DATEADD('day', -(MOD(ABS(HASH(RISK_ID || 'sd')), 7)), SNAPSHOT_DATE),
    CAMPAIGN_ID = CASE
        WHEN MOD(ABS(HASH(RISK_ID || 'cmp')), 100) < 40
        THEN 'CMP-' || LPAD((MOD(ABS(HASH(RISK_ID || 'cmp2')), 20) + 1)::VARCHAR, 3, '0')
        ELSE NULL
    END
WHERE CUSTOMER_LIFETIME_VALUE IS NULL;

