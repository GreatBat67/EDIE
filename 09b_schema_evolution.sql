-- 3. POLICIES — Rename 3 columns, add 7 new columns
-- ############################################################################

-- Renames
ALTER TABLE POLICIES RENAME COLUMN PLAN_TIER TO COVERAGE_TIER;
ALTER TABLE POLICIES RENAME COLUMN START_DATE TO EFFECTIVE_DATE;
ALTER TABLE POLICIES RENAME COLUMN END_DATE TO EXPIRATION_DATE;

-- Widen types for compatibility
ALTER TABLE POLICIES ALTER COLUMN POLICY_TYPE SET DATA TYPE VARCHAR(30);
ALTER TABLE POLICIES ALTER COLUMN COVERAGE_TIER SET DATA TYPE VARCHAR(15);

-- Add new columns
ALTER TABLE POLICIES ADD COLUMN IF NOT EXISTS POLICY_NUMBER VARCHAR(30);
ALTER TABLE POLICIES ADD COLUMN IF NOT EXISTS LINE_OF_BUSINESS VARCHAR(40);
ALTER TABLE POLICIES ADD COLUMN IF NOT EXISTS BOUND_DATE DATE;
ALTER TABLE POLICIES ADD COLUMN IF NOT EXISTS POLICY_TERM_MONTHS NUMBER(3,0);
ALTER TABLE POLICIES ADD COLUMN IF NOT EXISTS ISSUING_STATE VARCHAR(2);
ALTER TABLE POLICIES ADD COLUMN IF NOT EXISTS ENDORSEMENT_TYPE VARCHAR(30);
ALTER TABLE POLICIES ADD COLUMN IF NOT EXISTS EXPENSE_AMOUNT NUMBER(12,2);

UPDATE POLICIES SET
    POLICY_NUMBER = 'PN-' || REPLACE(POLICY_ID, 'POL-', '') || '-' ||
        LPAD(MOD(ABS(HASH(POLICY_ID || 'pn')), 99)::VARCHAR, 2, '0'),
    LINE_OF_BUSINESS = CASE POLICY_TYPE
        WHEN 'Auto' THEN 'Personal Auto'
        WHEN 'Home' THEN 'Homeowners'
        WHEN 'Life' THEN 'Individual Life'
        WHEN 'Health' THEN 'Group Health'
        WHEN 'Commercial' THEN 'Commercial Lines'
        ELSE 'Specialty'
    END,
    BOUND_DATE = DATEADD('day', -(1 + MOD(ABS(HASH(POLICY_ID || 'bd')), 14)), EFFECTIVE_DATE),
    POLICY_TERM_MONTHS = ROUND(DATEDIFF('month', EFFECTIVE_DATE, EXPIRATION_DATE)),
    ISSUING_STATE = (SELECT c.STATE FROM CUSTOMERS c WHERE c.CUSTOMER_ID = POLICIES.CUSTOMER_ID LIMIT 1),
    ENDORSEMENT_TYPE = CASE
        WHEN MOD(ABS(HASH(POLICY_ID || 'et')), 100) < 15 THEN 'Rider'
        WHEN MOD(ABS(HASH(POLICY_ID || 'et')), 100) < 25 THEN 'AdditionalInsured'
        WHEN MOD(ABS(HASH(POLICY_ID || 'et')), 100) < 32 THEN 'Waiver'
        WHEN MOD(ABS(HASH(POLICY_ID || 'et')), 100) < 38 THEN 'CoverageExtension'
        ELSE NULL
    END,
    EXPENSE_AMOUNT = ROUND(PREMIUM_AMOUNT * (0.15 + MOD(ABS(HASH(POLICY_ID || 'ea')), 200) / 1000.0), 2)
WHERE POLICY_NUMBER IS NULL;

-- Fix any NULL ISSUING_STATE from the subquery
UPDATE POLICIES SET ISSUING_STATE = 'CA' WHERE ISSUING_STATE IS NULL;


-- ############################################################################
-- 4. CLAIMS — Add 9 columns (ESCALATION_FLAG handled in 10_close_kpi_gaps)
-- ############################################################################

ALTER TABLE CLAIMS ALTER COLUMN STATUS SET DATA TYPE VARCHAR(20);
ALTER TABLE CLAIMS ALTER COLUMN CAUSE_OF_LOSS SET DATA TYPE VARCHAR(30);

ALTER TABLE CLAIMS ADD COLUMN IF NOT EXISTS LOSS_DATE DATE;
ALTER TABLE CLAIMS ADD COLUMN IF NOT EXISTS FNOL_DATE DATE;
ALTER TABLE CLAIMS ADD COLUMN IF NOT EXISTS FNOL_CHANNEL VARCHAR(15);
ALTER TABLE CLAIMS ADD COLUMN IF NOT EXISTS REPORTED_BY VARCHAR(15);
ALTER TABLE CLAIMS ADD COLUMN IF NOT EXISTS RESERVE_AMOUNT NUMBER(12,2);
ALTER TABLE CLAIMS ADD COLUMN IF NOT EXISTS PAID_AMOUNT NUMBER(12,2) DEFAULT 0;
ALTER TABLE CLAIMS ADD COLUMN IF NOT EXISTS RECOVERY_AMOUNT NUMBER(12,2) DEFAULT 0;
ALTER TABLE CLAIMS ADD COLUMN IF NOT EXISTS LITIGATION_FLAG BOOLEAN DEFAULT FALSE;
ALTER TABLE CLAIMS ADD COLUMN IF NOT EXISTS CATASTROPHE_CODE VARCHAR(20);

UPDATE CLAIMS SET
    LOSS_DATE = DATEADD('day', -(MOD(ABS(HASH(CLAIM_ID || 'ld')), 8)), CLAIM_DATE),
    FNOL_DATE = DATEADD('day', MOD(ABS(HASH(CLAIM_ID || 'fn')), 4), CLAIM_DATE),
    FNOL_CHANNEL = CASE MOD(ABS(HASH(CLAIM_ID || 'fc')), 5)
        WHEN 0 THEN 'Phone' WHEN 1 THEN 'Web' WHEN 2 THEN 'Email'
        WHEN 3 THEN 'Agent' ELSE 'MobileApp' END,
    REPORTED_BY = CASE MOD(ABS(HASH(CLAIM_ID || 'rb')), 5)
        WHEN 0 THEN 'Policyholder' WHEN 1 THEN 'Policyholder' WHEN 2 THEN 'Agent'
        WHEN 3 THEN 'ThirdParty' ELSE 'Policyholder' END,
    RESERVE_AMOUNT = CASE
        WHEN STATUS IN ('Open','UnderInvestigation') THEN ROUND(CLAIM_AMOUNT * (0.8 + MOD(ABS(HASH(CLAIM_ID || 'ra')), 40) / 100.0), 2)
        ELSE APPROVED_AMOUNT
    END,
    PAID_AMOUNT = CASE
        WHEN STATUS IN ('Closed','Approved','PartiallyPaid') AND APPROVED_AMOUNT IS NOT NULL
        THEN ROUND(APPROVED_AMOUNT * (0.7 + MOD(ABS(HASH(CLAIM_ID || 'pa')), 30) / 100.0), 2)
        ELSE 0
    END,
    RECOVERY_AMOUNT = CASE
        WHEN STATUS IN ('Closed','Subrogation') AND MOD(ABS(HASH(CLAIM_ID || 'rc')), 100) < 15
        THEN ROUND(CLAIM_AMOUNT * (0.05 + MOD(ABS(HASH(CLAIM_ID || 'rc2')), 20) / 100.0), 2)
        ELSE 0
    END,
    LITIGATION_FLAG = CASE
        WHEN MOD(ABS(HASH(CLAIM_ID || 'lit')), 100) < 5 THEN TRUE
        WHEN CLAIM_AMOUNT > 12000 AND MOD(ABS(HASH(CLAIM_ID || 'lit2')), 100) < 15 THEN TRUE
        ELSE FALSE
    END,
    CATASTROPHE_CODE = CASE
        WHEN CAUSE_OF_LOSS IN ('Hurricane/Tropical Storm','Natural Disaster','Weather Event')
        THEN 'CAT-' || LPAD(MOD(ABS(HASH(CLAIM_ID || 'cat')), 20 + 1)::VARCHAR, 3, '0')
        ELSE NULL
    END
WHERE LOSS_DATE IS NULL;


